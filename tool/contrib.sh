#!/usr/bin/env bash
set -euo pipefail

# Contributors whose names match this pattern are excluded.
EXCLUDE_PATTERN='fujidaiti|Daichi Fujita|\[bot\]|^Claude( |$)'

echo "<!-- THIS FILE WAS GENERATED BY tool/contrib.sh. DO NOT EDIT MANUALLY. -->"
echo "# Contributors"
echo
echo "Thank you for all contributors!"
echo

# Co-authors are credited in addition to commit authors, since
# squash-merged PRs list them only in Co-authored-by trailers.
git shortlog -n \
  --group=author \
  --group=trailer:co-authored-by \
  --format="%s - [%h](https://github.com/fujidaiti/smooth_sheets/commit/%h)" \
  HEAD \
  | EXCLUDE_PATTERN="$EXCLUDE_PATTERN" awk '
      # A divider between contributors
      /^[ \t]*$/ {
        if (!skip) print ""
        next
      }
      # E.g., "- ContributorName (3):"
      /^[^ \t]/ {
        name = $0
        sub(/ \([0-9]+\):$/, "", name)
        skip = (name ~ ENVIRON["EXCLUDE_PATTERN"])
        if (!skip) print "- " $0
        next
      }
      # E.g., "  - Commit message"
      {
        if (skip) next
        gsub(/^[ \t]+/, "")
        print "  - " $0
      }
  '
